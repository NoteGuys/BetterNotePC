let inMemoryLanguage = 'th';

/**
 * Get current application language ('th' | 'en')
 */
export const getAppLanguage = () => {
  try {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
      if (saved === 'en' || saved === 'th') return saved;
    }
  } catch (_) {}
  return inMemoryLanguage || 'th';
};

/**
 * Change application language and dispatch reactive update event
 */
export const setAppLanguage = (lang) => {
  const normalized = lang === 'en' ? 'en' : 'th';
  inMemoryLanguage = normalized;
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, normalized);
    }
    // Also sync to editor preferences storage directly
    try {
      const raw = localStorage.getItem('betternote_user_preferences');
      const prefs = raw ? JSON.parse(raw) : {};
      prefs.language = normalized;
      localStorage.setItem('betternote_user_preferences', JSON.stringify(prefs));
    } catch (_) {}

    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.setAttribute('lang', normalized);
    }
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent(LANGUAGE_EVENT_NAME, { detail: normalized }));
    }
  } catch (_) {}
  return normalized;
};

/**
 * Translation helper function with parameter replacement
 */
export const t = (key, fallback = '', params = {}) => {
  const lang = getAppLanguage();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.th;
  let text = '';
  if (dict && dict[key] !== undefined) {
    text = dict[key];
  } else if (TRANSLATIONS.en[key] !== undefined) {
    text = TRANSLATIONS.en[key];
  } else if (TRANSLATIONS.th[key] !== undefined) {
    text = TRANSLATIONS.th[key];
  } else {
    text = fallback || key;
  }

  // Replace {param} placeholders if any
  if (params && typeof params === 'object') {
    Object.keys(params).forEach(p => {
      text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
    });
  }
  return text;
};

/**
 * React Hook for reactive language updates
 */
export const useLanguage = () => {
  const [lang, setLang] = React.useState(() => getAppLanguage());

  React.useEffect(() => {
    const handleLanguageChange = (e) => {
      setLang(e.detail);
    };
    window.addEventListener(LANGUAGE_EVENT_NAME, handleLanguageChange);
    return () => {
      window.removeEventListener(LANGUAGE_EVENT_NAME, handleLanguageChange);
    };
  }, []);

  const translate = React.useCallback((key, fallback = '', params = {}) => {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS.th;
    let text = '';
    if (dict && dict[key] !== undefined) {
      text = dict[key];
    } else if (TRANSLATIONS.en[key] !== undefined) {
      text = TRANSLATIONS.en[key];
    } else if (TRANSLATIONS.th[key] !== undefined) {
      text = TRANSLATIONS.th[key];
    } else {
      text = fallback || key;
    }

    if (params && typeof params === 'object') {
      Object.keys(params).forEach(p => {
        text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
      });
    }
    return text;
  }, [lang]);

  return {
    language: lang,
    setLanguage: setAppLanguage,
    t: translate
  };
};

